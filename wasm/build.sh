#!/bin/bash
# wasm/build.sh — Compile NetHack 5.0 (C + Lua) to plain JavaScript.
#
# Pipeline: upstream NetHack 5.0 source + the contest recorder patches
# (nethack-c/patches/) + our port patches (wasm/patches/) → emcc
# (clang → WebAssembly) → wasm2js (WebAssembly → JavaScript).  The
# output js/nethack-c.js is an ES module with no WebAssembly at run
# time: the wasm is translated to asm.js-style JavaScript.
#
# Because the C is the recorder's own C, the PRNG stream, the screen
# capture (nomux shadow buffer) and every game rule come out the same
# as in the C recordings.  js/jsmain.js drives it: keys in, one screen
# per input boundary out.
#
# Usage:
#   bash wasm/build.sh            # full build → js/nethack-c.js
#   bash wasm/build.sh prepare    # only create the patched source tree
#
# Env:
#   NETHACK_UPSTREAM  NetHack 5.0 source (default nethack-c/upstream)
#   NETHACK_DATADIR   installed data files from the native recorder build
#                     (default nethack-c/recorder/install/games/lib/nethackdir)
#   EMSDK             emsdk checkout (default .cache/emsdk)
#   BUILD_DIR         scratch dir (default .cache/jsbuild)
#   OPT               optimization flags (default -O2)

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UPSTREAM="${NETHACK_UPSTREAM:-$ROOT/nethack-c/upstream}"
DATADIR="${NETHACK_DATADIR:-$ROOT/nethack-c/recorder/install/games/lib/nethackdir}"
EMSDK="${EMSDK:-$ROOT/.cache/emsdk}"
B="${BUILD_DIR:-$ROOT/.cache/jsbuild}"
OPT="${OPT:--O2}"
LUAVER=5.4.8
T="$B/tree"

if [ ! -f "$UPSTREAM/include/patchlevel.h" ]; then
    echo "[FAIL] NetHack source not found at $UPSTREAM (set NETHACK_UPSTREAM)" >&2
    exit 1
fi
if [ ! -f "$UPSTREAM/lib/lua-$LUAVER/src/lua.h" ]; then
    echo "[FAIL] Lua $LUAVER not found under $UPSTREAM/lib (see CLAUDE.md)" >&2
    exit 1
fi

MODE="${1:-all}"   # all | prepare | link

# --- 1. patched source tree ---------------------------------------------
if [ "$MODE" != link ]; then
echo "[1] source tree: $T"
rm -rf "$T"
mkdir -p "$T"
rsync -a --exclude='.git' --exclude='*.o' --exclude='*.a' "$UPSTREAM/" "$T/"
# Same method as nethack-c/build-recorder.sh: a throwaway git index so
# `git apply --recount` verifies every hunk.  The git dir lives outside
# the tree (and is not named .git) so it never touches this repository.
G="$B/git-apply"
rm -rf "$G"
export GIT_DIR="$G" GIT_WORK_TREE="$T"
git init -q
git -c gc.auto=0 add -A
git -c user.email=build@local -c user.name=build commit -q -m baseline
for p in "$ROOT"/nethack-c/patches/*.patch "$ROOT"/wasm/patches/*.patch; do
    [ -f "$p" ] || continue
    echo "    patch $(basename "$p")"
    ( cd "$T" && git apply --recount "$p" )
done
unset GIT_DIR GIT_WORK_TREE
rm -rf "$G"
cat > "$T/include/nhlua.h" <<EOF
/* nhlua.h - generated by wasm/build.sh (same as the top Makefile) */
#include "../lib/lua-$LUAVER/src/lua.h"
ATTRNORETURN LUA_API int   (lua_error) (lua_State *L) NORETURN;
#include "../lib/lua-$LUAVER/src/lualib.h"
#include "../lib/lua-$LUAVER/src/lauxlib.h"
/*nhlua.h*/
EOF
fi
cp "$ROOT/wasm/jsglue.c" "$T/src/jsglue.c"   # always fresh, even in link mode
rm -f "$B/obj/nh/jsglue.o"
[ "$MODE" = prepare ] && exit 0

# --- 2. toolchain ----------------------------------------------------------
if ! command -v emcc >/dev/null 2>&1; then
    if [ -f "$EMSDK/emsdk_env.sh" ]; then
        # shellcheck disable=SC1091
        source "$EMSDK/emsdk_env.sh" >/dev/null 2>&1
    fi
fi
command -v emcc >/dev/null 2>&1 || { echo "[FAIL] emcc not found (install emsdk into $EMSDK)" >&2; exit 1; }

OBJ="$B/obj"
mkdir -p "$OBJ/lua" "$OBJ/nh"

# --- 3. Lua -----------------------------------------------------------------
LUASRC="$T/lib/lua-$LUAVER/src"
compile() {   # compile <src> <obj> <flags...>; skipped in link mode
    local src="$1" obj="$2"; shift 2
    if [ "$MODE" = link ] && [ -f "$obj" ]; then return 0; fi
    emcc $OPT "$@" -c "$src" -o "$obj"
}
echo "[3] Lua $LUAVER"
LUAOBJS=()
for c in lapi lcode lctype ldebug ldo ldump lfunc lgc llex lmem lobject \
         lopcodes lparser lstate lstring ltable ltm lundump lvm lzio \
         lauxlib lbaselib lcorolib ldblib liolib lmathlib loadlib loslib \
         lstrlib ltablib lutf8lib linit; do
    o="$OBJ/lua/$c.o"
    compile "$LUASRC/$c.c" "$o" -DLUA_USE_POSIX &
    LUAOBJS+=("$o")
done
wait

# --- 4. NetHack ---------------------------------------------------------------
echo "[4] NetHack"
# __APPLE__/__MACH__: the recorder was built on macOS; config1.h turns these
# into MACOS, which selects the same port behavior (PORT_ID "MacOS", config
# file lookup, unixconf.h choices) as the recordings.
# NO_TERMCAP_HEADERS: wintty.h declares the termcap calls itself; they are
# served by wasm/jsglue.c, and wasm/include/curses.h stands in for ncurses.
NHFLAGS=(-I"$T/include" -I"$LUASRC" -I"$ROOT/wasm/include" -DNOTPARMDECL
         -DNO_TIMED_DELAY -DNO_TERMCAP_HEADERS -D__APPLE__ -D__MACH__
         -Wno-everything)
SRCS=()
for f in "$T"/src/*.c; do
    case "$(basename "$f")" in
        tile.c|cppregex.c|pmatchregex.c) continue ;;
    esac
    SRCS+=("$f")
done
SRCS+=("$T/sys/share/ioctl.c" "$T/sys/share/unixtty.c" "$T/sys/share/posixregex.c"
       "$T/sys/unix/unixmain.c" "$T/sys/unix/unixunix.c" "$T/sys/unix/unixres.c"
       "$T/win/tty/getline.c" "$T/win/tty/termcap.c" "$T/win/tty/topl.c"
       "$T/win/tty/wintty.c")
NHOBJS=()
n=0
for f in "${SRCS[@]}"; do
    o="$OBJ/nh/$(basename "$f" .c).o"
    # compile from src/ with the same relative paths as the recorder's
    # Makefile, so __FILE__ in the PRNG log reads "o_init.c:89"
    case "$f" in
        "$T"/src/*) rel="${f#"$T"/src/}" ;;
        *)          rel="../${f#"$T"/}" ;;
    esac
    ( cd "$T/src" && compile "$rel" "$o" "${NHFLAGS[@]}" ) &
    NHOBJS+=("$o")
    n=$((n + 1))
    if [ $((n % 16)) -eq 0 ]; then wait; fi
done
wait

# --- 5. data files ------------------------------------------------------------
echo "[5] data files from $DATADIR"
D="$B/nethackdir"
rm -rf "$D"
mkdir -p "$D/save"
for f in "$DATADIR"/*; do
    name="$(basename "$f")"
    [ -f "$f" ] || continue
    case "$name" in
        nethack|recover|record|xlogfile|logfile|livelog|paniclog|perm) continue ;;
        alock.*|block.*|bon*|*.0|*wizard*|*recorder*|*agent*) continue ;;
    esac
    cp "$f" "$D/$name"
done
# empty score files, as the recorder harness leaves them before a session
: > "$D/record"; : > "$D/xlogfile"; : > "$D/logfile"; : > "$D/perm"
cp "$ROOT/wasm/sysconf" "$D/sysconf"

# --- 6. link → js/nethack-c.js -----------------------------------------------
echo "[6] link (wasm2js)"
emcc $OPT "${NHOBJS[@]}" "${LUAOBJS[@]}" -o "$B/nethack-c.mjs" \
    -sWASM=0 -sMODULARIZE=1 -sEXPORT_ES6=1 -sEXPORT_NAME=createNetHack \
    -sENVIRONMENT=web -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=33554432 \
    -sSTACK_SIZE=1048576 -sSUPPORT_LONGJMP=emscripten -sEXIT_RUNTIME=0 \
    -sFORCE_FILESYSTEM=1 -sEXPORTED_RUNTIME_METHODS=FS,ENV,callMain,UTF8ToString \
    -sINVOKE_RUN=0 -sDYNAMIC_EXECUTION=0 \
    --embed-file "$D@/nh" 2>&1 | grep -v 'WASM=0 is deprecated' || true
cp "$B/nethack-c.mjs" "$ROOT/js/nethack-c.js"
ls -la "$ROOT/js/nethack-c.js"
echo "[ok] built js/nethack-c.js"
